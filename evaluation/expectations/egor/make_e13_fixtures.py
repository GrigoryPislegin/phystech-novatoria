def facts_of(*pairs):
    return [{'id': f'f{i}', 'text': text, 'quote': quote} for i, (text, quote) in enumerate(pairs, 1)]


def posting(job_id, title, intro, must, nice, terms, conditions=()):
    """A vacancy with the usual sections. A mandatory requirement cites the heading down to its own line,
    as SYSTEM asks for a heading-defined obligation."""
    heading = 'Обязательные требования:'
    text = '\n'.join([title, intro, heading, *('— ' + line[1] for line in must), 'Будет плюсом:',
                      *('— ' + line[1] for line in nice), 'Условия:', *('— ' + t for t in terms)])
    start = text.index(heading)
    lines = [(name, quote, text[start:text.index(quote) + len(quote)], status, ids, comment)
             for name, quote, status, ids, comment in must]
    lines += [(name, quote, False, status, ids, comment) for name, quote, status, ids, comment in nice]
    return vacancy(job_id, title, text, lines, conditions)


def condition(kind, state, fact_id, cv_quote, vacancy_quote, note):
    return {'kind': kind, 'state': state, 'cv': {'fact_id': fact_id, 'quote': cv_quote},
            'vacancy_quote': vacancy_quote, 'note': note}


